def _require(condition: bool, message: str) -> None:
    if not condition:
        raise RuntimeError(f"architecture atlas: {message}")


def _form(value: Any, operator: str | None = None) -> tuple[str, str, dict, list]:
    _require(isinstance(value, list) and len(value) >= 3,
             "every form must be [operator id attributes ...]")
    op, form_id, attributes, *children = value
    _require(isinstance(op, str) and isinstance(form_id, str),
             "form operator and id must be strings")
    _require(isinstance(attributes, dict), f"{op} {form_id} attributes must be a map")
    if operator is not None:
        _require(op == operator, f"expected {operator}, got {op}")
    return op, form_id, attributes, children


def _validate_model(value: Any, context: str) -> None:
    if isinstance(value, list):
        _require(value, f"{context} model vectors cannot be empty")
        if not isinstance(value[0], str):
            _require(all(item is None or isinstance(item, str | bool | int | float)
                         for item in value),
                     f"{context} data vectors must contain scalar values")
        for child in value[1:]:
            _validate_model(child, context)
        return
    if isinstance(value, dict):
        _require(all(isinstance(key, str) for key in value),
                 f"{context} model map keys must be strings")
        for child in value.values():
            _validate_model(child, context)
        return
    _require(value is None or isinstance(value, str | bool | int | float),
             f"{context} model contains unsupported {type(value).__name__}")


def load_document() -> dict[str, Any]:
    """Validate and normalize the canonical documentation AST."""
    root = load_edn(DOC_SOURCE_PATH)
    op, atlas_id, metadata, children = _form(root, "defatlas")
    del op
    _require(metadata.get("schema_version") == 1, "schema_version must be 1")
    _require(metadata.get("tiers") == list(TIERS), "tier order is fixed")

    sources: dict[str, dict] = {}
    views: dict[str, dict] = {}
    chapter_forms: list[tuple[str, dict, list]] = []
    for child in children:
        child_op, child_id, attributes, grandchildren = _form(child)
        _require(child_op in {"source", "view", "chapter"},
                 f"unknown top-level form {child_op}")
        if child_op == "source":
            _require(not grandchildren, f"source {child_id} cannot have children")
            _require(child_id not in sources, f"duplicate source {child_id}")
            _require(all(isinstance(attributes.get(key), str)
                         for key in ("path", "symbol", "role")),
                     f"source {child_id} is incomplete")
            _require((ROOT / attributes["path"]).is_file(),
                     f"source {child_id} path does not exist")
            sources[child_id] = {"id": child_id, **attributes}
        elif child_op == "view":
            _require(not grandchildren, f"view {child_id} cannot have children")
            _require(child_id not in views, f"duplicate view {child_id}")
            _require(attributes.get("dimension") in {0, 1, 2, 3, 4},
                     f"view {child_id} has invalid dimension")
            _require(isinstance(attributes.get("alt"), str) and attributes["alt"],
                     f"view {child_id} needs alt text")
            nodes = attributes.get("nodes")
            edges = attributes.get("edges")
            _require(isinstance(nodes, list) and nodes, f"view {child_id} needs nodes")
            _require(isinstance(edges, list), f"view {child_id} needs edges")
            node_ids = [node.get("id") for node in nodes if isinstance(node, dict)]
            _require(len(node_ids) == len(nodes) == len(set(node_ids)),
                     f"view {child_id} node ids must be unique")
            for node in nodes:
                _require(all(key in node for key in ("label", "detail", "x", "y")),
                         f"view {child_id} has incomplete node")
            for edge in edges:
                _require(isinstance(edge, list) and len(edge) == 3,
                         f"view {child_id} edges are [from to label]")
                _require(edge[0] in node_ids and edge[1] in node_ids,
                         f"view {child_id} edge does not resolve")
            views[child_id] = {"id": child_id, **attributes}
        else:
            chapter_forms.append((child_id, attributes, grandchildren))

    chapters = []
    chapter_ids = set()
    for chapter_id, attributes, tier_forms in chapter_forms:
        _require(chapter_id not in chapter_ids, f"duplicate chapter {chapter_id}")
        chapter_ids.add(chapter_id)
        _require(attributes.get("view") in views,
                 f"chapter {chapter_id} view does not resolve")
        source_ids = attributes.get("sources")
        _require(isinstance(source_ids, list) and source_ids,
                 f"chapter {chapter_id} needs sources")
        _require(all(source_id in sources for source_id in source_ids),
                 f"chapter {chapter_id} source does not resolve")
        tiers = []
        for tier_form in tier_forms:
            tier_op, tier_id, tier, grandchildren = _form(tier_form, "tier")
            del tier_op
            _require(not grandchildren, f"tier {chapter_id}/{tier_id} cannot nest forms")
            required = ("label", "summary", "prose", "insights", "pitfalls", "model")
            _require(all(key in tier for key in required),
                     f"tier {chapter_id}/{tier_id} is incomplete")
            _require(isinstance(tier["prose"], list) and tier["prose"],
                     f"tier {chapter_id}/{tier_id} needs prose")
            _require(isinstance(tier["insights"], list) and tier["insights"],
                     f"tier {chapter_id}/{tier_id} needs insights")
            _require(isinstance(tier["pitfalls"], list) and tier["pitfalls"],
                     f"tier {chapter_id}/{tier_id} needs pitfalls")
            _validate_model(tier["model"], f"tier {chapter_id}/{tier_id}")
            tiers.append({"id": tier_id, **tier})
        _require(tuple(tier["id"] for tier in tiers) == TIERS,
                 f"chapter {chapter_id} must contain all tiers in order")
        chapters.append({"id": chapter_id, **attributes, "tiers": tiers})

    chapters.sort(key=lambda chapter: chapter["order"])
    _require([chapter["order"] for chapter in chapters]
             == list(range(1, len(chapters) + 1)),
             "chapter order must be contiguous")
    return {
        "schema": DOC_SCHEMA,
        "id": atlas_id,
        **metadata,
        "chapters": chapters,
        "views": views,
        "sources": sources,
        "denotation": root,
    }


def _json_value(value: Any) -> Any:
    if isinstance(value, np.ndarray):
        return value.tolist()
    if isinstance(value, np.generic):
        return value.item()
    if isinstance(value, Enum):
        return {"name": value.name.lower(), "value": int(value.value)}
    if is_dataclass(value):
        return {
            field.name: _json_value(getattr(value, field.name))
            for field in fields(value)
            if field.init
        }
    if isinstance(value, Sequence) and not isinstance(value, str | bytes):
        return [_json_value(item) for item in value]
    if isinstance(value, Mapping):
        return {str(key): _json_value(item) for key, item in value.items()}
    if value is None or isinstance(value, str | bool | int | float):
        return value
    raise TypeError(f"cannot serialize atlas value {type(value).__name__}")


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    digest.update(path.read_bytes())
    return digest.hexdigest()


def _dsl_atom(value: Any) -> str:
    if value is None:
        return "nil"
    if value is True:
        return "true"
    if value is False:
        return "false"
    if isinstance(value, str):
        if re.fullmatch(r"[A-Za-z][A-Za-z0-9+*/?!_.:/-]*", value):
            return value
        return json.dumps(value, ensure_ascii=False)
    return str(value)


def _sexpr(value: Any, indent: int = 0) -> str:
    """Pretty-print a compact Clojure-like projection of an AST value."""
    if isinstance(value, dict):
        items = []
        for key, child in value.items():
            items.append(f":{key} {_sexpr(child, indent + 2)}")
        inline = "{" + " ".join(items) + "}"
        if len(inline) <= 92 and "\n" not in inline:
            return inline
        pad = " " * (indent + 2)
        return "{\n" + pad + ("\n" + pad).join(items) + "\n" + " " * indent + "}"
    if isinstance(value, list):
        if not value:
            return "[]"
        children = [_sexpr(child, indent + 2) for child in value]
        inline = "(" + " ".join(children) + ")"
        if len(inline) <= 92 and all("\n" not in child for child in children):
            return inline
        pad = " " * (indent + 2)
        return "(" + children[0] + "\n" + pad + ("\n" + pad).join(children[1:]) + ")"
    return _dsl_atom(value)


def _svg_for_view(view: dict[str, Any]) -> str:
    nodes = view["nodes"]
    timeline = view["projection"] == "timeline"
    node_width = 124 if timeline else 180
    node_height = 62
    node_by_id = {node["id"]: node for node in nodes}
    parts = [
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1000 350" role="img" '
        f'aria-labelledby="title desc">',
        f'<title id="title">{escape(view["title"])}</title>',
        f'<desc id="desc">{escape(view["alt"])}</desc>',
        '<defs><marker id="arrow" markerWidth="8" markerHeight="8" refX="7" refY="4" '
        'orient="auto"><path d="M0,0 L8,4 L0,8 z" fill="#687672"/></marker></defs>',
        '<rect width="1000" height="350" rx="12" fill="#f4efe4"/>',
    ]
    for source_id, target_id, label in view["edges"]:
        source = node_by_id[source_id]
        target = node_by_id[target_id]
        sx = source["x"] + node_width
        sy = source["y"] + node_height / 2
        tx = target["x"]
        ty = target["y"] + node_height / 2
        bend = max(28, abs(tx - sx) * .42)
        if tx >= sx:
            path = f"M {sx} {sy} C {sx + bend} {sy}, {tx - bend} {ty}, {tx} {ty}"
        else:
            lower = max(sy, ty) + 72
            path = f"M {sx} {sy} C {sx + 36} {lower}, {tx - 36} {lower}, {tx} {ty}"
        parts.append(
            f'<path d="{path}" fill="none" stroke="#687672" stroke-width="1.7" '
            'marker-end="url(#arrow)"/>')
        if label:
            lx = (sx + tx) / 2
            ly = (sy + ty) / 2 - 7
            parts.append(
                f'<text x="{lx}" y="{ly}" text-anchor="middle" fill="#687672" '
                f'font-family="ui-monospace,monospace" font-size="10">{escape(label)}</text>')
    palette = ("#d97928", "#168da0", "#3c75aa", "#d02a91", "#64766f")
    for index, node in enumerate(nodes):
        color = "#d97928" if node["id"] == "m20" else palette[index % len(palette)]
        parts.extend([
            f'<g id="{escape(node["id"])}" transform="translate({node["x"]} {node["y"]})">',
            f'<rect width="{node_width}" height="{node_height}" rx="7" fill="#fffdf7" '
            f'stroke="{color}" stroke-width="2"/>',
            f'<rect width="5" height="{node_height}" rx="3" fill="{color}"/>',
            f'<text x="14" y="24" fill="#202827" font-family="system-ui,sans-serif" '
            f'font-size="13" font-weight="700">{escape(node["label"])}</text>',
            f'<text x="14" y="44" fill="#5a6864" font-family="system-ui,sans-serif" '
            f'font-size="10.5">{escape(node["detail"])}</text>',
            '</g>',
        ])
    parts.append(
        f'<text x="18" y="336" fill="#687672" font-family="ui-monospace,monospace" '
        f'font-size="11">{escape(str(view["dimension"]))}D domain → {escape(view["projection"])}</text>')
    parts.append('</svg>\n')
    return "\n".join(parts)


def _markdown_table(table: dict[str, Any]) -> list[str]:
    headers = table["headers"]
    rows = table["rows"]
    return [
        "| " + " | ".join(headers) + " |",
        "| " + " | ".join("---" for _ in headers) + " |",
        *("| " + " | ".join(row) + " |" for row in rows),
    ]


def _chapter_markdown(document: dict[str, Any], chapter: dict[str, Any]) -> str:
    view = document["views"][chapter["view"]]
    lines = [
        GENERATED_NOTICE,
        "",
        f"# {chapter['title']}",
        "",
        f"> {chapter['subtitle']}",
        "",
        "[Architecture atlas](README.md) · "
        "[Interactive proof atlas](../../atlas/README.md) · "
        "[Roadmap](../../ROADMAP.md)",
        "",
        f"![{view['alt']}](assets/{view['id']}.svg)",
        "",
    ]
    for tier_number, tier in enumerate(chapter["tiers"], start=1):
        lines.extend([
            f"## Tier {tier_number} — {tier['label']}",
            "",
            f"**{tier['summary']}**",
            "",
        ])
        for paragraph in tier["prose"]:
            lines.extend([paragraph, ""])
        lines.extend(["### Compact architecture form", "", "```clojure",
                      _sexpr(tier["model"]), "```", "", "### Key insights", ""])
        lines.extend(f"- {item}" for item in tier["insights"])
        lines.extend(["", "### Common pitfalls", ""])
        lines.extend(f"- {item}" for item in tier["pitfalls"])
        lines.append("")
        if "table" in tier:
            lines.extend(_markdown_table(tier["table"]))
            lines.append("")
    lines.extend(["## Source trail", ""])
    for source_id in chapter["sources"]:
        source = document["sources"][source_id]
        lines.append(
            f"- [`{source['path']}`](../../{source['path']}) — "
            f"{source['symbol']}; {source['role']}.")
    lines.extend(["", "---", ""])
    chapters = document["chapters"]
    index = chapters.index(chapter)
    neighbors = []
    if index:
        previous = chapters[index - 1]
        neighbors.append(f"← [{previous['title']}]({previous['id']}.md)")
    if index + 1 < len(chapters):
        following = chapters[index + 1]
        neighbors.append(f"[{following['title']}]({following['id']}.md) →")
    lines.extend([" · ".join(neighbors), ""])
    return "\n".join(lines)


