def _stable_plan_projection(graph, plan):
    """Return one stable valid order for documentation serialization.

    ``compile_pipeline`` permits independent ready nodes to appear in either
    order because runtime semantics do not depend on that choice. The atlas
    needs byte-stable output across Python hash seeds, so it projects the same
    dependency DAG with authored-node order as the deterministic tie-breaker.
    """
    authored_order = {node.node_id: index for index, node in enumerate(graph.nodes)}
    by_id = {step.node.node_id: step for step in plan.steps}
    dependencies: dict[str, set[str]] = {}
    children: dict[str, set[str]] = {node_id: set() for node_id in by_id}
    for node_id, step in by_id.items():
        required = {
            ref.node for name, ref in step.inputs.items()
            if name not in step.definition.delayed_inputs and ref.node in by_id
        }
        dependencies[node_id] = required
        for parent in required:
            children[parent].add(node_id)
    ready = sorted(
        (node_id for node_id, required in dependencies.items() if not required),
        key=authored_order.__getitem__)
    ordered = []
    while ready:
        node_id = ready.pop(0)
        ordered.append(by_id[node_id])
        for child in sorted(children[node_id], key=authored_order.__getitem__):
            dependencies[child].discard(node_id)
            if not dependencies[child] and by_id[child] not in ordered:
                if child not in ready:
                    ready.append(child)
    if len(ordered) != len(plan.steps):
        raise RuntimeError("atlas could not canonicalize compiled pipeline")
    return tuple(ordered)


def _pipeline_payload(integrator: IntegratorConfig, replay) -> dict[str, Any]:
    graph = pipeline_from_integrator(
        integrator, graph_id="atlas/proof-pixel",
        title="Proof-pixel ReSTIR PT")
    plan = compile_pipeline(
        graph, builtin_operator_catalog(), backend="scalar",
        terminals=("frame", "radiance", "beauty"))
    projected = pipeline_replay(graph, replay)
    stable_steps = _stable_plan_projection(graph, plan)
    groups = []
    transport_nodes = tuple(
        step.node.node_id for step in stable_steps
        if step.definition.category in ("Direct", "Indirect"))
    stable_groups = []
    for step in stable_steps:
        if step.definition.category in ("Direct", "Indirect"):
            continue
        if step.definition.operator_id == "render.standard_frame":
            stable_groups.append((*transport_nodes, step.node.node_id))
        else:
            stable_groups.append((step.node.node_id,))
    for index, nodes in enumerate(stable_groups):
        groups.append({"id": f"dispatch-{index}", "nodes": list(nodes)})

    step_index = {
        step.node.node_id: index for index, step in enumerate(stable_steps)}
    consumers = {}
    for index, step in enumerate(stable_steps):
        for input_name, ref in step.inputs.items():
            if input_name not in step.definition.delayed_inputs:
                consumers.setdefault((ref.node, ref.port), []).append(index)
    terminals = {
        (ref.node, ref.port) for ref in plan.terminal_refs.values()}
    resources = []
    for step in stable_steps:
        first = step_index[step.node.node_id]
        for port, spec in step.definition.outputs.items():
            key = (step.node.node_id, port)
            resources.append({
                "node": key[0], "port": key[1], "first_step": first,
                "last_step": max(consumers.get(key, (first,))),
                "retained": key in terminals, "kind": spec.kind,
            })
    return {
        "authored": graph.to_dict(),
        "semantic_hash": graph.semantic_hash,
        "compiled": {
            "backend": plan.backend,
            "terminals": list(plan.terminals),
            "steps": [{
                "node": step.node.node_id,
                "operator": step.definition.operator_id,
                "category": step.definition.category,
                "parameters": _json_value(step.parameters),
            } for step in stable_steps],
            "fused_groups": groups,
            "resources": resources,
            "delayed_nodes": list(plan.delayed_nodes),
        },
        "record_projection": [{
            "node": item.node_id,
            "operator": item.operator_id,
            "sample": item.sample_index,
            "payload_type": type(item.payload).__name__,
        } for item in projected.operators],
    }


def _entities(document: dict[str, Any], sample) -> dict[str, Any]:
    entities: dict[str, Any] = {}
    for chapter in document["chapters"]:
        entities[f"chapter:{chapter['id']}"] = {
            "kind": "chapter", "chapter": chapter["id"],
            "tier": "orientation", "label": chapter["title"],
        }
        for tier in chapter["tiers"]:
            entities[f"tier:{chapter['id']}:{tier['id']}"] = {
                "kind": "tier", "chapter": chapter["id"],
                "tier": tier["id"], "label": tier["label"],
            }
    for index, vertex in enumerate(sample.indirect.vertices):
        entities[f"vertex:{index}"] = {
            "kind": "path-vertex", "chapter": "proof",
            "tier": "working-model", "stage": "fresh",
            "label": f"Path vertex {vertex.depth}", "record_index": index,
        }
    for index, contribution in enumerate(sample.indirect.contributions):
        entities[f"contribution:{index}"] = {
            "kind": "path-contribution", "chapter": "proof",
            "tier": "working-model", "stage": "fresh",
            "label": f"Contribution {contribution.contribution_index}",
            "record_index": index,
        }
    for index, _update in enumerate(sample.fresh_path_reservoir):
        entities[f"fresh:{index}"] = {
            "kind": "reservoir-update", "chapter": "proof",
            "tier": "working-model", "stage": "fresh",
            "label": f"Fresh update {index + 1}", "record_index": index,
        }
    for index, _shift in enumerate(sample.temporal_shifts):
        entities[f"temporal:{index}"] = {
            "kind": "temporal-shift", "chapter": "proof",
            "tier": "proof-and-source", "stage": "temporal",
            "label": "Temporal shift", "record_index": index,
        }
    for index, shift in enumerate(sample.spatial_shifts):
        entities[f"spatial:{index}"] = {
            "kind": "spatial-shift", "chapter": "proof",
            "tier": "proof-and-source", "stage": "spatial",
            "label": f"Spatial attempt {index}", "record_index": index,
            "status": "valid" if shift.valid else "failed",
        }
    entities["final:reservoir"] = {
        "kind": "final-reservoir", "chapter": "proof",
        "tier": "proof-and-source", "stage": "evaluate",
        "label": "Final path reservoir", "record_index": 0,
    }
    return entities


def _validate_canonical(replay, expected: dict[str, Any]) -> None:
    if len(replay.samples) != 1:
        raise RuntimeError("atlas fixture must contain exactly one sample")
    sample = replay.samples[0]
    if sample.indirect is None:
        raise RuntimeError("atlas fixture lost its indirect trace")
    actual_shape = {
        "vertices": 6,
        "contributions": 5,
        "fresh_updates": 5,
        "temporal": 1,
        "spatial": 6,
        "valid_spatial": 3,
        "failed_spatial": 3,
        "accepted_spatial": 2,
    }
    actual = {
        "vertices": len(sample.indirect.vertices),
        "contributions": len(sample.indirect.contributions),
        "fresh_updates": len(sample.fresh_path_reservoir),
        "temporal": len(sample.temporal_shifts),
        "spatial": len(sample.spatial_shifts),
        "valid_spatial": sum(item.valid for item in sample.spatial_shifts),
        "failed_spatial": sum(not item.valid for item in sample.spatial_shifts),
        "accepted_spatial": sum(item.accepted for item in sample.spatial_shifts),
    }
    authored_shape = {key: expected[key] for key in actual_shape}
    if actual != authored_shape:
        raise RuntimeError(
            f"canonical atlas pixel changed: expected {authored_shape}, got {actual}")
    temporal = sample.temporal_shifts[0]
    if (not temporal.valid or not temporal.accepted
            or temporal.hybrid_shift is None
            or temporal.hybrid_shift.mapping.name.lower()
            != expected["temporal_mapping"]):
        raise RuntimeError("canonical temporal hybrid reconnection changed")
    if not sample.final_path_reservoir:
        raise RuntimeError("canonical final path reservoir disappeared")
    final = sample.final_path_reservoir[-1]
    if (final.M != expected["final_M"] or final.selected_temporal_shift is None
            or final.selected_spatial_shift is None):
        raise RuntimeError("canonical final reservoir lineage changed")


def generate(destination: Path, docs_destination: Path | None = None) -> None:
    destination.mkdir(parents=True, exist_ok=True)
    document = load_document()
    proof = load_edn(PROOF_PATH)
    if proof.get("schema_version") != 1:
        raise RuntimeError("proof-pixel schema_version must be 1")
    resolution = proof["resolution"]
    source = scene_dict(proof["scene"])
    scene = lower_scene(source)
    camera = _camera(source, resolution)
    path_config = proof["integrator"]
    if path_config.get("mode") != "restir_pt":
        raise RuntimeError("proof-pixel integrator must be restir_pt")
    integrator = IntegratorConfig(
        indirect=PathEstimatorConfig.restir_pt(
            max_depth=path_config["max_depth"],
            temporal_m_cap=path_config["temporal_m_cap"],
            spatial_mode=path_config["spatial_mode"],
            spatial_neighbors=path_config["spatial_neighbors"],
            spatial_radius=path_config["spatial_radius"]))

    frame4 = scalar.render_frame(
        scene, camera, 1, frame=proof["source_frame"], integrator=integrator)
    history = PathTemporalHistory.capture(scene, camera, frame4)
    frame5 = scalar.render_frame(
        scene, camera, 1, frame=proof["target_frame"], integrator=integrator,
        path_temporal_history=history)
    x, y = proof["pixel"]
    replay = replay_pixel(
        scene, camera,
        PixelSelection(x, y, proof["target_frame"], 1, integrator=integrator),
        path_temporal_history=history,
        path_spatial_source=frame5.path_spatial_source)
    _validate_canonical(replay, proof["expected"])
    sample = replay.samples[0]

    source_image = f"frame-{proof['source_frame']}.png"
    target_image = f"frame-{proof['target_frame']}.png"
    write_png(str(destination / source_image),
              tonemap(frame4.radiance, proof["exposure"]))
    write_png(str(destination / target_image),
              tonemap(frame5.radiance, proof["exposure"]))
    bounds = debug_bounds(scene, camera)

    payload = {
        "schema": SCHEMA,
        "document": document,
        "metadata": {
            "fixture": proof["fixture_id"],
            "scene": proof["scene"],
            "resolution": [resolution, resolution],
            "source_frame": proof["source_frame"],
            "target_frame": proof["target_frame"],
            "pixel": proof["pixel"],
            "sample": proof["sample"],
            "backend": "scalar",
            "policy": "exact/unbiased",
            "integrator": _json_value(integrator),
        },
        "entities": _entities(document, sample),
        "scene": {
            "authored": source,
            "wireframe": scene_wireframe(scene, camera).tolist(),
            "bounds": {"center": bounds.center.tolist(),
                       "radius": bounds.radius},
            "image_plane": image_plane(camera, bounds).tolist(),
        },
        "frames": {
            "source": {"frame": proof["source_frame"],
                       "image": f"generated/{source_image}"},
            "target": {"frame": proof["target_frame"],
                       "image": f"generated/{target_image}"},
        },
        "pipeline": _pipeline_payload(integrator, replay),
        "replay": _json_value(replay),
        "summary": {
            "path_vertices": len(sample.indirect.vertices),
            "contributions": len(sample.indirect.contributions),
            "fresh_updates": len(sample.fresh_path_reservoir),
            "temporal_attempts": len(sample.temporal_shifts),
            "spatial_attempts": len(sample.spatial_shifts),
            "valid_spatial": sum(item.valid for item in sample.spatial_shifts),
            "failed_spatial": sum(not item.valid for item in sample.spatial_shifts),
            "accepted_spatial": sum(item.accepted for item in sample.spatial_shifts),
            "final_M": sample.final_path_reservoir[-1].M,
            "final_W": sample.final_path_reservoir[-1].W,
            "sample_radiance": sample.sample_radiance.tolist(),
        },
    }
    data_path = destination / "atlas-v2.json"
    data_path.write_text(
        json.dumps(payload, indent=2, sort_keys=True, allow_nan=False) + "\n",
        encoding="utf-8")
    generated_names = ("atlas-v2.json", source_image, target_image)
    manifest = {
        "schema": SCHEMA,
        "files": {
            name: _sha256(destination / name)
            for name in generated_names
        },
    }
    (destination / "manifest.json").write_text(
        json.dumps(manifest, indent=2, sort_keys=True) + "\n",
        encoding="utf-8")
    if docs_destination is not None:
        generate_docs(document, docs_destination)


def _relative_files(root: Path) -> list[Path]:
    return sorted(path.relative_to(root) for path in root.rglob("*") if path.is_file())


def check() -> None:
    with tempfile.TemporaryDirectory(prefix="restir-atlas-") as temporary:
        root = Path(temporary)
        target = root / "atlas"
        docs_target = root / "docs"
        generate(target, docs_target)
        expected = _relative_files(target)
        actual = (_relative_files(GENERATED_DIR)
                  if GENERATED_DIR.exists() else [])
        if actual != expected:
            raise SystemExit(
                f"generated atlas file set drifted: expected {expected}, got {actual}")
        drifted = [str(name) for name in expected
                   if (target / name).read_bytes()
                   != (GENERATED_DIR / name).read_bytes()]
        if drifted:
            raise SystemExit(
                "generated atlas artifacts drifted: " + ", ".join(drifted))
        expected_docs = _relative_files(docs_target)
        actual_docs = sorted(
            path.relative_to(DOC_OUTPUT_DIR)
            for path in DOC_OUTPUT_DIR.rglob("*")
            if path.is_file() and path != DOC_SOURCE_PATH)
        if actual_docs != expected_docs:
            raise SystemExit(
                f"generated docs file set drifted: expected {expected_docs}, got {actual_docs}")
        drifted_docs = [str(name) for name in expected_docs
                        if (docs_target / name).read_bytes()
                        != (DOC_OUTPUT_DIR / name).read_bytes()]
        if drifted_docs:
            raise SystemExit(
                "generated docs artifacts drifted: " + ", ".join(drifted_docs))


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true",
        help="regenerate in a temporary directory and fail on drift")
    args = parser.parse_args(argv)
    if args.check:
        check()
        print("atlas generated artifacts are current")
        return
    if GENERATED_DIR.exists():
        shutil.rmtree(GENERATED_DIR)
    generate(GENERATED_DIR, DOC_OUTPUT_DIR)
    print(
        f"wrote atlas artifacts to {GENERATED_DIR.relative_to(ROOT)} "
        f"and documentation to {DOC_OUTPUT_DIR.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
