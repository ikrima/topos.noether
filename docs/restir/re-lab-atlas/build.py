def generate_docs(document: dict[str, Any], destination: Path) -> None:
    destination.mkdir(parents=True, exist_ok=True)
    for markdown in destination.glob("*.md"):
        if markdown.read_text(encoding="utf-8").startswith(GENERATED_NOTICE):
            markdown.unlink()
    assets = destination / "assets"
    if assets.exists():
        shutil.rmtree(assets)
    assets.mkdir()
    (destination / "README.md").write_text(
        _index_markdown(document), encoding="utf-8")
    for chapter in document["chapters"]:
        (destination / f"{chapter['id']}.md").write_text(
            _chapter_markdown(document, chapter), encoding="utf-8")
        view = document["views"][chapter["view"]]
        (assets / f"{view['id']}.svg").write_text(
            _svg_for_view(view), encoding="utf-8")


